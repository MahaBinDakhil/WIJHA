<?php
/* =====================================================
   logout.php — تسجيل الخروج
   يمسح بيانات الجلسة ويرجّع لصفحة الدخول
   ===================================================== */
require_once __DIR__ . '/../includes/db.php';

$_SESSION = [];          // نفضّي كل بيانات الجلسة
session_destroy();       // ننهي الجلسة

// نبدأ جلسة جديدة فاضية بس عشان نعرض رسالة الخروج
session_start();
set_flash('success', 'تم تسجيل الخروج بنجاح');

header('Location: login.php');
exit;
