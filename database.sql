CREATE DATABASE IF NOT EXISTS rihla_db
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE rihla_db;

DROP TABLE IF EXISTS bookings;
DROP TABLE IF EXISTS tours;
DROP TABLE IF EXISTS cities;
DROP TABLE IF EXISTS admins;

-- ---------- 1) المشرفين ----------
CREATE TABLE admins (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  username   VARCHAR(50)  NOT NULL UNIQUE,
  password   VARCHAR(255) NOT NULL,          -- مشفرة بـ password_hash
  full_name  VARCHAR(100)
) ENGINE=InnoDB;

-- ---------- 2) المدن ----------
CREATE TABLE cities (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  name        VARCHAR(50)  NOT NULL UNIQUE,
  description VARCHAR(255),
  image       VARCHAR(255)                -- صورة المدينة للرئيسية
) ENGINE=InnoDB;

-- ---------- 3) الجولات ----------
CREATE TABLE tours (
  id              INT AUTO_INCREMENT PRIMARY KEY,
  city_id         INT NOT NULL,
  created_by      INT,                        -- المشرف اللي أضاف الجولة
  title           VARCHAR(100) NOT NULL,
  type            ENUM('تاريخية','طبيعة','مغامرات','ثقافية') NOT NULL,
  short_desc      VARCHAR(200) NOT NULL,
  description     TEXT NOT NULL,
  itinerary       TEXT,                       -- برنامج الجولة
  meeting_point   VARCHAR(150),               -- نقطة التجمع
  includes        VARCHAR(255),               -- يشمل
  tour_date       DATE NOT NULL,              -- تاريخ الرحلة
  duration        VARCHAR(30)  NOT NULL,      -- مثال: 3 ساعات
  price           DECIMAL(8,2) NOT NULL CHECK (price > 0),
  available_seats INT NOT NULL DEFAULT 0 CHECK (available_seats >= 0),
  image           VARCHAR(255) NOT NULL,
  is_featured     TINYINT(1) DEFAULT 0,       -- يظهر في الرئيسية
  created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_tour_city FOREIGN KEY (city_id)
    REFERENCES cities(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_tour_admin FOREIGN KEY (created_by)
    REFERENCES admins(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------- 4) الحجوزات ----------
CREATE TABLE bookings (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  tour_id       INT NOT NULL,
  customer_name VARCHAR(100) NOT NULL,
  phone         VARCHAR(10)  NOT NULL,
  email         VARCHAR(100) NOT NULL,
  persons       INT NOT NULL CHECK (persons > 0),
  total_price   DECIMAL(10,2) NOT NULL,
  status        ENUM('جديد','مؤكد','ملغي') DEFAULT 'جديد',
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_booking_tour FOREIGN KEY (tour_id)
    REFERENCES tours(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

